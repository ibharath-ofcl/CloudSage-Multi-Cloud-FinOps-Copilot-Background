"""
CloudSage Remediation Playbook Generator.
Generates deterministic, production-grade Infrastructure-as-Code (Terraform, CloudFormation, Bicep)
and Cloud CLI remediation scripts (AWS CLI, Azure CLI, GCP gcloud) for optimization recommendations
and waste findings.
STRICTLY ADVISORY-ONLY: CloudSage provides advisory code for human review; it never executes cloud mutations.
"""

from decimal import Decimal
import re
from typing import Any, Dict, List, Optional
from uuid import UUID

from backend.app.core.enums import CloudProvider, RecommendationAction


def sanitize_identifier(identifier: Optional[str]) -> str:
    """Sanitizes resource identifiers against shell and template injection."""
    if not identifier:
        return "resource-placeholder"
    # Keep alphanumeric, hyphens, underscores, slashes, colons, dots
    cleaned = re.sub(r"[^a-zA-Z0-9_\-\./:]", "", str(identifier))
    return cleaned or "resource-placeholder"


class RemediationPlaybookGenerator:
    """
    Generates multi-format remediation playbooks with clear advisory disclaimers,
    rollback procedures, and post-execution verification checks.
    """

    ADVISORY_HEADER = """# ==============================================================================
# CLOUDSAGE ADVISORY REMEDIATION PLAYBOOK
# ------------------------------------------------------------------------------
# NOTICE: This is an advisory script generated by CloudSage FinOps Copilot.
# CloudSage adheres to strict non-destructive FinOps principles and NEVER executes
# cloud mutations directly.
#
# INSTRUCTIONS:
# 1. Review all actions with your infrastructure team.
# 2. Test in a non-production environment before applying to production.
# 3. Follow your organization's standard change management process.
# ==============================================================================
"""

    @classmethod
    def generate_playbook(
        cls,
        provider: str,
        action_type: str,
        resource_id: str,
        resource_name: Optional[str] = None,
        region: Optional[str] = None,
        account_id: Optional[str] = None,
        service_name: Optional[str] = None,
        estimated_monthly_savings: Optional[Decimal] = None,
        details: Optional[Dict[str, Any]] = None,
        playbook_format: str = "markdown",
    ) -> Dict[str, str]:
        """
        Generates playbook content for the requested format.
        Returns a dict with format, content, filename, and mime_type.
        """
        fmt = playbook_format.lower().strip()
        prov = provider.upper().strip()
        act = action_type.upper().strip()
        res_id = sanitize_identifier(resource_id)
        res_name = sanitize_identifier(resource_name or resource_id)
        reg = sanitize_identifier(region or "us-east-1")
        acct = sanitize_identifier(account_id or "primary-account")
        svc = service_name or "Compute"
        savings = estimated_monthly_savings or Decimal("0.0000")
        meta = details or {}

        generators = {
            "terraform": cls._generate_terraform,
            "tf": cls._generate_terraform,
            "cloudformation": cls._generate_cloudformation,
            "cfn": cls._generate_cloudformation,
            "aws_cli": cls._generate_aws_cli,
            "azure_cli": cls._generate_azure_cli,
            "gcp_cli": cls._generate_gcp_cli,
            "bicep": cls._generate_azure_bicep,
            "azure_bicep": cls._generate_azure_bicep,
            "markdown": cls._generate_markdown,
            "md": cls._generate_markdown,
        }

        gen_func = generators.get(fmt, cls._generate_markdown)
        content, filename, mime_type = gen_func(
            prov=prov,
            act=act,
            res_id=res_id,
            res_name=res_name,
            reg=reg,
            acct=acct,
            svc=svc,
            savings=savings,
            meta=meta,
        )

        return {
            "format": fmt,
            "content": content,
            "filename": filename,
            "mime_type": mime_type,
            "provider": prov,
            "action_type": act,
            "estimated_monthly_savings": str(savings),
        }

    @classmethod
    def _generate_terraform(cls, prov: str, act: str, res_id: str, res_name: str, reg: str, acct: str, svc: str, savings: Decimal, meta: Dict[str, Any]) -> tuple:
        target_type = meta.get("recommended_type") or "t3.medium"
        content = f"""{cls.ADVISORY_HEADER}
# Target Cloud Provider: {prov}
# Target Resource: {res_id}
# Action: {act}
# Projected Monthly Savings: ${savings} USD

terraform {{
  required_version = ">= 1.5.0"
}}

# Step 1: Manage resource state or update declaration
"""
        if "TERMINATE" in act or "DELETE" in act or "CLEANUP" in act:
            content += f"""# To decommission this idle or unattached resource:
# Option A: Remove the corresponding resource block from your Terraform codebase,
# then run:
#   terraform plan -target=<resource_address>
#   terraform apply -target=<resource_address>

# Option B: Or declare state removal:
#   terraform state rm aws_instance.{res_name.replace('-', '_')}
"""
        elif "RIGHTSIZE" in act:
            content += f"""# To rightsize this instance to target size '{target_type}':
# Update your Terraform resource block:
# resource "{prov.lower()}_instance" "{res_name.replace('-', '_')}" {{
#   instance_type = "{target_type}" # Downsized from current baseline
#   # Preserve existing tags and subnets
# }}
"""
        else:
            content += f"""# Update resource configuration in Terraform:
# Target Resource ID: {res_id}
# Apply recommended configuration tags or tier conversion.
"""

        content += f"""
# ==============================================================================
# ROLLBACK PLAN:
# If workload degradation is observed post-application:
# 1. Revert Git commit containing Terraform definition changes.
# 2. Run: terraform apply
# ==============================================================================
"""
        return content, f"remediate_{res_name}.tf", "text/x-terraform"

    @classmethod
    def _generate_cloudformation(cls, prov: str, act: str, res_id: str, res_name: str, reg: str, acct: str, svc: str, savings: Decimal, meta: Dict[str, Any]) -> tuple:
        target_type = meta.get("recommended_type") or "t3.medium"
        content = f"""{cls.ADVISORY_HEADER}
# AWS CloudFormation Advisory Template
# Resource: {res_id}
# Projected Savings: ${savings} USD/mo

AWSTemplateFormatVersion: '2010-09-09'
Description: 'CloudSage FinOps Advisory Remediation - {act} for {res_id}'

Parameters:
  Environment:
    Type: String
    Default: 'production'
  TargetInstanceType:
    Type: String
    Default: '{target_type}'

# Guidance:
# To apply via AWS CLI:
# aws cloudformation update-stack --stack-name <your-stack> --template-body file://template.yaml
"""
        return content, f"remediate_{res_name}.yaml", "application/x-yaml"

    @classmethod
    def _generate_aws_cli(cls, prov: str, act: str, res_id: str, res_name: str, reg: str, acct: str, svc: str, savings: Decimal, meta: Dict[str, Any]) -> tuple:
        target_type = meta.get("recommended_type") or "t3.medium"
        content = f"""#!/usr/bin/env bash
{cls.ADVISORY_HEADER}
set -euo pipefail

# Configuration
REGION="${{AWS_DEFAULT_REGION:-{reg}}}"
RESOURCE_ID="{res_id}"
SAVINGS_USD="{savings}"

echo ">>> Initiating CloudSage Advisory Action: {act} for ${{RESOURCE_ID}}"
echo ">>> Region: ${{REGION}} | Expected Monthly Savings: $${{SAVINGS_USD}}"

# 1. Pre-execution verification
echo ">>> Step 1: Checking current resource status..."
"""
        if "TERMINATE" in act or "IDLE" in act:
            content += f"""aws ec2 describe-instances --instance-ids "${{RESOURCE_ID}}" --region "${{REGION}}" --query 'Reservations[*].Instances[*].[InstanceId,State.Name,InstanceType]' --output table

# 2. Safety snapshot / stop
read -p "Do you wish to proceed with stopping instance ${{RESOURCE_ID}}? [y/N] " -n 1 -r
echo
if [[ $REPLY =~ ^[Yy]$ ]]; then
  echo ">>> Stopping instance (allows non-destructive verification)..."
  aws ec2 stop-instances --instance-ids "${{RESOURCE_ID}}" --region "${{REGION}}"
  echo ">>> Instance stopped. Validate workload before terminating."
fi

# Rollback:
# aws ec2 start-instances --instance-ids "${{RESOURCE_ID}}" --region "${{REGION}}"
"""
        elif "DELETE" in act or "SNAPSHOT" in act:
            content += f"""aws ec2 describe-snapshots --snapshot-ids "${{RESOURCE_ID}}" --region "${{REGION}}" --output table

read -p "Confirm deletion of orphaned snapshot ${{RESOURCE_ID}}? [y/N] " -n 1 -r
echo
if [[ $REPLY =~ ^[Yy]$ ]]; then
  aws ec2 delete-snapshot --snapshot-id "${{RESOURCE_ID}}" --region "${{REGION}}"
  echo ">>> Snapshot ${{RESOURCE_ID}} successfully removed."
fi
"""
        elif "RIGHTSIZE" in act:
            content += f"""echo ">>> Current instance type check:"
aws ec2 describe-instances --instance-ids "${{RESOURCE_ID}}" --region "${{REGION}}" --query 'Reservations[*].Instances[*].[InstanceId,InstanceType]' --output table

echo ">>> Target instance type: {target_type}"
read -p "Stop and modify instance type to {target_type}? [y/N] " -n 1 -r
echo
if [[ $REPLY =~ ^[Yy]$ ]]; then
  aws ec2 stop-instances --instance-ids "${{RESOURCE_ID}}" --region "${{REGION}}"
  aws ec2 wait instance-stopped --instance-ids "${{RESOURCE_ID}}" --region "${{REGION}}"
  aws ec2 modify-instance-attribute --instance-id "${{RESOURCE_ID}}" --instance-type "Value={target_type}" --region "${{REGION}}"
  aws ec2 start-instances --instance-ids "${{RESOURCE_ID}}" --region "${{REGION}}"
  echo ">>> Instance ${{RESOURCE_ID}} rightsized to {target_type}."
fi
"""
        elif "RELEASE" in act or "IP" in act:
            content += f"""read -p "Release unattached Elastic IP allocation ${{RESOURCE_ID}}? [y/N] " -n 1 -r
echo
if [[ $REPLY =~ ^[Yy]$ ]]; then
  aws ec2 release-address --allocation-id "${{RESOURCE_ID}}" --region "${{REGION}}"
  echo ">>> Elastic IP ${{RESOURCE_ID}} released."
fi
"""
        else:
            content += f"""echo ">>> Performing advisory inspection on ${{RESOURCE_ID}}..."
aws ec2 describe-volumes --volume-ids "${{RESOURCE_ID}}" --region "${{REGION}}" || true
"""

        return content, f"remediate_{res_name}_aws.sh", "application/x-sh"

    @classmethod
    def _generate_azure_cli(cls, prov: str, act: str, res_id: str, res_name: str, reg: str, acct: str, svc: str, savings: Decimal, meta: Dict[str, Any]) -> tuple:
        content = f"""#!/usr/bin/env bash
{cls.ADVISORY_HEADER}
set -euo pipefail

RESOURCE_ID="{res_id}"
RESOURCE_GROUP="${{AZURE_RESOURCE_GROUP:-rg-finops}}"
SUBSCRIPTION_ID="${{AZURE_SUBSCRIPTION_ID:-{acct}}}"

echo ">>> CloudSage Advisory Action: {act} for ${{RESOURCE_ID}}"
echo ">>> Expected Monthly Savings: ${savings} USD"

az account set --subscription "${{SUBSCRIPTION_ID}}"

# Check existence
az resource show --ids "${{RESOURCE_ID}}" --output table

read -p "Confirm action {act} on Azure resource? [y/N] " -n 1 -r
echo
if [[ $REPLY =~ ^[Yy]$ ]]; then
  echo ">>> Executing advisory deallocation / cleanup..."
  az vm deallocate --ids "${{RESOURCE_ID}}" || az resource delete --ids "${{RESOURCE_ID}}"
fi
"""
        return content, f"remediate_{res_name}_azure.sh", "application/x-sh"

    @classmethod
    def _generate_azure_bicep(cls, prov: str, act: str, res_id: str, res_name: str, reg: str, acct: str, svc: str, savings: Decimal, meta: Dict[str, Any]) -> tuple:
        target_sku = meta.get("recommended_type") or "Standard_B2s"
        content = f"""// {cls.ADVISORY_HEADER}
// Azure Bicep Advisory Template
// Target Resource: {res_id}
// Projected Monthly Savings: ${savings} USD

param location string = '{reg}'
param vmName string = '{res_name}'
param vmSize string = '{target_sku}'

// Deploy via:
// az deployment group create --resource-group <rg> --template-file template.bicep
"""
        return content, f"remediate_{res_name}.bicep", "text/plain"

    @classmethod
    def _generate_gcp_cli(cls, prov: str, act: str, res_id: str, res_name: str, reg: str, acct: str, svc: str, savings: Decimal, meta: Dict[str, Any]) -> tuple:
        target_machine = meta.get("recommended_type") or "e2-medium"
        content = f"""#!/usr/bin/env bash
{cls.ADVISORY_HEADER}
set -euo pipefail

PROJECT_ID="${{GCP_PROJECT_ID:-{acct}}}"
ZONE="${{GCP_ZONE:-{reg}-a}}"
INSTANCE_NAME="{res_name}"

echo ">>> CloudSage Advisory Action: {act} for GCP Instance ${{INSTANCE_NAME}}"
echo ">>> Projected Savings: ${savings} USD/mo"

# Verification
gcloud compute instances describe "${{INSTANCE_NAME}}" --project="${{PROJECT_ID}}" --zone="${{ZONE}}" --format="table(name,status,machineType)"

read -p "Confirm stopping or rightsizing ${{INSTANCE_NAME}}? [y/N] " -n 1 -r
echo
if [[ $REPLY =~ ^[Yy]$ ]]; then
  gcloud compute instances stop "${{INSTANCE_NAME}}" --project="${{PROJECT_ID}}" --zone="${{ZONE}}"
  echo ">>> Instance ${{INSTANCE_NAME}} stopped safely."
fi

# Rollback:
# gcloud compute instances start "${{INSTANCE_NAME}}" --project="${{PROJECT_ID}}" --zone="${{ZONE}}"
"""
        return content, f"remediate_{res_name}_gcp.sh", "application/x-sh"

    @classmethod
    def _generate_markdown(cls, prov: str, act: str, res_id: str, res_name: str, reg: str, acct: str, svc: str, savings: Decimal, meta: Dict[str, Any]) -> tuple:
        target_type = meta.get("recommended_type") or "Optimized Tier"
        content = f"""# CloudSage Advisory Remediation Playbook

> **STRICT ADVISORY NOTICE**: CloudSage is an advisory FinOps copilot. No cloud mutations are performed autonomously. All commands must be reviewed and executed by authorized personnel.

---

### Executive Summary

| Parameter | Value |
|:---|:---|
| **Cloud Provider** | `{prov}` |
| **Service** | `{svc}` |
| **Resource Identifier** | `{res_id}` |
| **Recommended Action** | `{act}` |
| **Projected Monthly Savings** | **${savings} USD** |
| **Target Sizing / Configuration** | `{target_type}` |
| **Region / Placement** | `{reg}` |
| **Account / Project** | `{acct}` |

---

### Step-by-Step Execution Guide

#### Step 1: Pre-Execution Verification
1. Inspect the resource in your cloud management console or CLI.
2. Ensure no mission-critical traffic or cron jobs are actively utilizing this asset.
3. Verify that an up-to-date backup or snapshot exists.

#### Step 2: Remediation Commands

```bash
# Verify resource state
aws ec2 describe-instances --instance-ids "{res_id}" --region "{reg}"

# Apply advisory modification
# Follow your organization's GitOps or Terraform deployment workflow
```

#### Step 3: Post-Remediation Verification
1. Monitor application telemetry (CPU, Memory, error rates) for 15-30 minutes.
2. Confirm the resource status has transitioned as expected.
3. Validate billing reporting in the subsequent ingestion cycle.

---

### Rollback Procedures

If unintended service disruption occurs:
1. Revert Terraform / Bicep changes and re-run pipeline.
2. Restore from pre-remediation backup/snapshot if deletion occurred.
3. Restart stopped instances via cloud console or CLI.
"""
        return content, f"remediate_{res_name}.md", "text/markdown"
